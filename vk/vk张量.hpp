//
//  本文件是默认唯一需要精读的文件。工作方式只有一条：调用下面的公开入口做
//  「通用算子调度」，其余实现一律当黑盒。
//
//  ── 只用这些入口 ────────────────────────────────────────────────────────
//  初始化（进程内一次）：
//    阶段配置 图形, 计算{阶段配置::自动队列族, 0, 2}, 传输;  // 计算阶段 2 条流
//    流水线调度器::获取().启动(设备注册信息{}, {图形, 计算, 传输}, "spv");
//  建张量 / 主机往返：
//    vk张量 甲(张量布局::连续(形状), 张量类型::浮点32, "甲");
//    甲.上传(...);  甲.下载(...);  甲.同步();  甲.仿形();
//  基础算子（结果张量自带缓冲，任务号由对象内部记账）：
//    vk张量 丙 = (甲 + 乙) * 甲 - 乙;          // + - * / 及 加法/减法/乘法/除法
//    vk张量 丁 = 甲.算子(张量算子::加法, 乙);   // 通用入口：算子由变量决定
//  自定义算子 / 多核 pass：
//    流水线调度器::获取().提交自定义算子(名字, {取句柄()...},
//                                        推送数据, 推送字节, 派发规格, 依赖);
//    流水线调度器::获取().提交算子串({构造算子步骤(...), ...});
//    输出.挂任务(编号);                        // 外部 pass 写完本张量后调用
//  自检：vk张量::断言算子可用(算子);  或  流水线调度器::获取().存在算子("名字")。
//  超出加减乘除的算子（matmul/rmsnorm/attention…）一律走 提交自定义算子 /
//  提交算子串，不要往 张量算子 枚举里加值，也不要改 算子() 的录制路径。
//
//  ── 以下由系统内部完成，不要手写、不要绕过 ──────────────────────────────
//  · 着色编译：glsl/*.comp → shader_tool → spv/*.spv + spv/*.spv.hpp。
//    build.bat 会自动跑这一步；其余直接调 cl 的脚本不会重编 shader，
//    改过 shader 就先跑 build.bat（或 shader_tool）。
//    新增算子时才需要：写 .comp、重跑上述编译、把生成的 spv/<名字>.spv.hpp
//    包含进编译单元。
//  · 布局与绑定：set 下标 = 张量下标、binding 0，绑定数/推送字节按 .spv.hpp
//    元信息校验；标准算子的推送常量与 1D 派发组数自动填。调用方不拼
//    VkDescriptorSet，不调 vkCmdDispatch，也不手工建管线。
//  · 资源回收：缓冲、描述符集、管线、命令流、设备都是 RAII；张量析构即还缓冲，
//    调度器 停止() 统一收尾，无需手工释放或跟踪句柄。
//  · 同步与依赖：(甲 + 乙) * 丙 这类表达式自动按数据流排队；上传/下载/同步
//    之前自动等待在途任务。调用方全程看不到任务编号。
//
//  ── 什么时候才需要打开别的文件 ──────────────────────────────────────────
//  · 新增算子：glsl/xxx.comp 显式写 layout(set=, binding=) → 跑着色编译
//    → 包含 spv/xxx.spv.hpp → 用 提交自定义算子 / 提交算子串 调用。到此为止。
//  · 加载报错：先读 断言算子可用 / 流水线调度器::获取().加载失败清单() 的文本；
//    确需排查再读 加载着色器()。
//  · 调度/依赖异常：只读 流水线调度器.hpp 的「提交 / 等待 / 停止」三节。
//  · 其余情况不要逐行阅读 流水线调度器.hpp、着色编译器.hpp、vk底层 的实现：
//    它们只决定“怎么做”，不改变你调用本文件的方式。
// ============================================================================
// ============================================================================
//  vk张量.hpp
//  Vulkan 底层封装 · 张量类（基础算数：加、减、乘、除）
//
//  设计要点：
//    1. 本类的两件事：
//       a) 算子胶水调度 —— 把张量折算成 张量句柄 交给 流水线调度器，
//          操作符（甲 + 乙）与具名接口（甲.加法(乙)）返回结果张量；
//       b) 张量数据搬运 —— 拷贝 / 拷贝到 / 上传 / 下载，字节数由张量自己算，
//          走 vk底层::缓冲 的读写口，全程不进调度器、不占命令流。
//       分工就一条：GLSL 源码归 着色编译器，它编成 .spv 二进制；.spv、逻辑设备、
//       命令流归 流水线调度器（设备由 vk底层 注册、由调度器持有）；
//       缓冲区里的数据归 vk张量。
//       底层资源全部委托 vk底层.hpp，本类不直接调用 vkCreateBuffer /
//       vkAllocateMemory 等原始接口，也不出现 VkCommandBuffer 与任务编号。
//       构造张量默认向调度器借它持有的设备（vk张量 甲(布局, 类型, "甲")），
//       张量只有使用权：调度器 停止() 放掉设备后，在世张量一并作废。
//    2. 算子不做本地注册表：布局与绑定由 流水线调度器 按 .spv 元信息推导。
//       本类只把「自己的缓冲 + 描述符集 + 形状」折算成 张量句柄 交出去。
//    3. 算子就是操作符：丙 = 甲 + 乙;  返回值是一个新的 vk张量（自带缓冲区），
//       加减乘除各有一条具名接口（甲.加法(乙)）与操作符同实现。
//       参数与返回值里都没有 VkCommandBuffer，也没有任务编号：
//       命令流、绑定、推送常量、派发规模全部由 流水线调度器 按 .spv 元信息推导。
//    4. 任务编号藏进张量内部：结果对象记住写它的那个任务，
//       于是 (甲 + 乙) * 丙 自动按数据流排队（参与运算的一侧未落地即成为前置依赖），
//       下载()/上传()/同步() 之前自动等待，用户全程看不到编号。
//    5. 校验只有一处：调度器 的 校验录制参数（张量个数、推送字节、同形状同类型），
//       在调用线程抛出；本类不重复三元组检查，避免两处规则漂移。
//    6. 张量句柄按值进任务闭包（shared_ptr），张量先析构不会让在途录制踩空。
// ============================================================================
