// ---- 构造：全部底层资源由 vk底层::设备 创建，本类只持智能指针 ----
inline vk张量::vk张量(vk底层::设备& 设备, 张量布局 布局, 张量类型 类型, std::string 名称,
                      bool 读多)
    : 设备_(&设备)
    , 布局_(std::move(布局))
    , 类型_(类型)
    , 名称_(std::move(名称))
{
    if (布局_.元素总数 == 0) throw std::runtime_error("张量元素总数为零");
    if (类型字节大小(类型_) == 0) throw std::runtime_error("未知的张量数据类型: " + 名称_);

    缓冲_     = 设备.创建存储缓冲(字节大小(), 读多);
    描述符集_ = 设备.分配缓冲描述符集(*缓冲_);

    if (!缓冲_ || !描述符集_) {
        throw std::runtime_error("创建张量底层资源失败: " + 名称_);
    }
}

inline vk张量::vk张量(vk底层::设备& 设备, 张量布局 布局, 张量类型 类型,
                      const void* 初始数据, std::size_t 字节数, std::string 名称,
                      bool 读多)
    : vk张量(设备, std::move(布局), 类型, std::move(名称), 读多)
{
    if (初始数据 && 字节数 > 0) 上传(初始数据, 字节数);
}

// 不带设备的两个：设备从调度器借，调度器没 启动() 就直接抛，别静默造个空张量
inline vk张量::vk张量(张量布局 布局, 张量类型 类型, std::string 名称, bool 读多)
    : vk张量(流水线调度器::获取().获取设备(), std::move(布局), 类型,
             std::move(名称), 读多) {}

inline vk张量::vk张量(张量布局 布局, 张量类型 类型, const void* 初始数据,
                      std::size_t 字节数, std::string 名称, bool 读多)
    : vk张量(流水线调度器::获取().获取设备(), std::move(布局), 类型,
             初始数据, 字节数, std::move(名称), 读多) {}

inline vk底层::设备& vk张量::设备() const {
    if (设备_ == nullptr) throw std::runtime_error("张量未绑定设备: " + 名称_);
    return *设备_;
}

inline vk张量 vk张量::仿形(std::string 新名称) const {
    return vk张量(设备(), 张量布局::连续(布局_.形状), 类型_, std::move(新名称));
}

// ---- 移动：任务编号跟着张量走，源对象清空，避免两处等同一个任务 ----
inline vk张量::vk张量(vk张量&& 其他) noexcept
    : 设备_(其他.设备_)
    , 缓冲_(std::move(其他.缓冲_))
    , 描述符集_(std::move(其他.描述符集_))
    , 布局_(std::move(其他.布局_))
    , 类型_(其他.类型_)
    , 名称_(std::move(其他.名称_))
    , 任务_(其他.任务_)
{
    其他.设备_ = nullptr;
    其他.任务_ = 0;
}

inline vk张量& vk张量::operator=(vk张量&& 其他) noexcept {
    if (this != &其他) {
        设备_     = 其他.设备_;
        缓冲_     = std::move(其他.缓冲_);
        描述符集_ = std::move(其他.描述符集_);
        布局_     = std::move(其他.布局_);
        类型_     = 其他.类型_;
        名称_     = std::move(其他.名称_);
        任务_     = 其他.任务_;
        其他.设备_ = nullptr;
        其他.任务_ = 0;
    }
    return *this;
}

// ---- 布局封装的核心 ----
inline 张量句柄 vk张量::取句柄() const {
    if (!有效()) throw std::runtime_error("张量未初始化: " + 名称_);
    张量句柄 句柄;
    句柄.缓冲      = 缓冲_;
    句柄.描述符集  = 描述符集_;
    句柄.元素总数  = 布局_.元素总数;
    句柄.元素字节  = static_cast<std::uint32_t>(类型字节大小(类型_));
    return 句柄;
}

// ---- 主机数据访问：读写之前先把写进本张量的算子等到落地 ----
inline void vk张量::同步() const {
    if (任务_ == 0) return;
    流水线调度器& 调度器 = 流水线调度器::获取();
    const std::uint64_t 编号 = 任务_;
    任务_ = 0;                       // 先清：抛错也不留下一个永远等不到的编号
    调度器.等待(编号);
    const 任务状态 状态 = 调度器.查询状态(编号);
    if (状态 == 任务状态::失败) {
        throw std::runtime_error("写进张量 " + 名称_ + " 的算子失败: "
                                 + 调度器.查询失败原因(编号));
    }
    if (状态 != 任务状态::完成) {
        throw std::runtime_error(std::string("写进张量 ") + 名称_ + " 的算子没有正常结束（状态 "
                                 + 任务状态名(状态) + "），检查调度器是否已 停止()");
    }
}

inline void vk张量::上传(const void* 数据, std::size_t 字节数) {
    if (!缓冲_) throw std::runtime_error("张量未初始化: " + 名称_);
    if (字节数 > 字节大小()) {
        throw std::runtime_error("上传字节数超出张量大小: " + 名称_ + " 容量 "
                                 + std::to_string(字节大小()) + " 请求 " + std::to_string(字节数));
    }
    同步();                          // 别把还在被算子读的缓冲改脏
    缓冲_->写入(数据, 字节数);
}

inline void vk张量::下载(void* 数据, std::size_t 字节数) const {
    if (!缓冲_) throw std::runtime_error("张量未初始化: " + 名称_);
    if (字节数 > 字节大小()) {
        throw std::runtime_error("下载字节数超出张量大小: " + 名称_);
    }
    同步();                          // 结果张量刚算出来就能直接读，不用管编号
    缓冲_->读取(数据, 字节数);
}

// ---- 张量拷贝：缓冲区对拷归本类，不进调度器也不碰命令流 ----
inline vk张量 vk张量::拷贝(std::string 新名称) const {
    vk张量 副本 = 仿形(std::move(新名称));
    拷贝到(副本);
    return 副本;
}

inline void vk张量::拷贝到(vk张量& 目标) const {
    if (!有效()) throw std::runtime_error("拷贝源张量未初始化: " + 名称_);
    if (!目标.有效()) throw std::runtime_error("拷贝目标张量未初始化: " + 目标.名称_);
    if (设备_ != 目标.设备_) {
        throw std::runtime_error("不支持跨设备拷贝: " + 名称_ + " → " + 目标.名称_
                                 + "（请先 下载 到主机再 上传）");
    }
    const std::size_t 字节 = 字节大小();
    if (字节 != 目标.字节大小()) {
        throw std::runtime_error("拷贝字节数不匹配：" + 名称_ + " " + std::to_string(字节)
                                 + " 字节，" + 目标.名称_ + " "
                                 + std::to_string(目标.字节大小()) + " 字节（整块对拷要求同大小）");
    }
    if (缓冲_ == 目标.缓冲_) {          // 同一块缓冲：没什么要搬的，等在途算子结束就够
        同步();
        return;
    }

    // 走的是和 上传/下载 同一条路：缓冲映射出来的读取 + 写入。
    // 所以两边在途的算子必须先落地，否则读到的不是最终值，或者覆盖掉还没读完的数据。
    同步();
    目标.同步();
    std::vector<std::uint8_t> 中转(字节);
    缓冲_->读取(中转.data(), 字节);
    目标.缓冲_->写入(中转.data(), 字节);
}

// ---- 可用性自检 ----
inline bool vk张量::算子可用(张量算子 算子) {
    return 流水线调度器::获取().存在算子(算子到文件名(算子));
}

inline void vk张量::断言算子可用(张量算子 算子) {
    const std::string 文件 = 算子到文件名(算子);
    if (流水线调度器::获取().查询元信息(文件) == nullptr) {
        throw std::runtime_error(std::string("算子 ") + 张量算子名(算子) + "（" + 文件
                                 + ".spv.hpp）的元信息未登记，检查生成头是否被包含");
    }
    if (!流水线调度器::获取().存在算子(文件)) {
        throw std::runtime_error(std::string("算子 ") + 张量算子名(算子) + "（" + 文件
                                 + ".spv）未加载，检查扫描目录与 启动() 传入的着色器目录");
    }
}

// ---- 算子通用实现：结果张量由本张量仿形，绑定与派发全在调度器 ----
inline vk张量 vk张量::算子(张量算子 算子类型, const vk张量& 乙,
                            std::string 新名称, int 优先级) const {
    断言算子可用(算子类型);
    vk张量 结果 = 仿形(std::move(新名称));

    // 表达式依赖自动串：甲、乙 各自还没落地的写入排在本算子之前，
    // 于是 (甲 + 乙) * 丙 这类写法天然按数据流顺序执行，调用方不碰任务编号。
    std::vector<std::uint64_t> 依赖 = 在途依赖();
    for (const std::uint64_t 编号 : 乙.在途依赖()) {
        bool 重复 = false;
        for (const std::uint64_t 已有 : 依赖) if (已有 == 编号) { 重复 = true; break; }
        if (!重复) 依赖.push_back(编号);
    }

    // 元素总数由调度器按句柄填进推送常量，本类不拼 push 结构
    结果.任务_ = 流水线调度器::获取().提交基础算子(
        算子到文件名(算子类型), {取句柄(), 乙.取句柄(), 结果.取句柄()}, 依赖, 优先级);
    return 结果;
}

