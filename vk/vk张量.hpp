// ---------------------------------------------------------------------------
// 数据类型
// ---------------------------------------------------------------------------
enum class 张量类型 : std::uint8_t {
    浮点32 = 0,
    浮点16 = 1,
    整数32 = 2,
    整数8  = 3,
    无符号8  = 4,
    无符号32 = 5,
    浮点bf16 = 6,   // 存储为 2 字节 bf16 位模式（buffer，无 VkFormat）
};

inline std::size_t 类型字节大小(张量类型 类型) {
    switch (类型) {
    case 张量类型::浮点32:   return 4;
    case 张量类型::浮点16:   return 2;
    case 张量类型::整数32:   return 4;
    case 张量类型::整数8:    return 1;
    case 张量类型::无符号8:  return 1;
    case 张量类型::无符号32: return 4;
    case 张量类型::浮点bf16: return 2;
    }
    return 0;
}

inline const char* 张量类型名(张量类型 类型) {
    switch (类型) {
    case 张量类型::浮点32:   return "fp32";
    case 张量类型::浮点16:   return "fp16";
    case 张量类型::整数32:   return "i32";
    case 张量类型::整数8:    return "i8";
    case 张量类型::无符号8:  return "u8";
    case 张量类型::无符号32: return "u32";
    case 张量类型::浮点bf16: return "bf16";
    }
    return "unknown";
}

// ---------------------------------------------------------------------------
// 布局：形状与步长（元素为单位）。基础实现只支持连续布局。
// ---------------------------------------------------------------------------
struct 张量布局 {
    std::vector<std::uint32_t> 形状;
    std::vector<std::uint32_t> 步长;
    std::uint32_t              元素总数 = 0;

    static 张量布局 连续(std::vector<std::uint32_t> 形状_) {
        张量布局 布局;
        布局.形状 = std::move(形状_);
        if (布局.形状.empty()) throw std::runtime_error("张量形状不能为空");
        for (std::uint32_t 维 : 布局.形状) {
            if (维 == 0) throw std::runtime_error("张量形状不允许为 0 维");
        }
        布局.步长.resize(布局.形状.size());
        std::uint32_t 累乘 = 1;
        for (int i = static_cast<int>(布局.形状.size()) - 1; i >= 0; --i) {
            布局.步长[i] = 累乘;
            累乘 *= 布局.形状[i];
        }
        布局.元素总数 = 累乘;
        return 布局;
    }

    bool 连续() const {
        if (形状.size() != 步长.size()) return false;
        std::uint32_t 累乘 = 1;
        for (int i = static_cast<int>(形状.size()) - 1; i >= 0; --i) {
            if (步长[i] != 累乘) return false;
            累乘 *= 形状[i];
        }
        return true;
    }

    // 形状是否等价：基础算子要求同形状
    bool 同形状(const 张量布局& 其他) const { return 形状 == 其他.形状; }
};

// ---------------------------------------------------------------------------
// 基础算子
// ---------------------------------------------------------------------------
enum class 张量算子 : std::uint8_t {
    加法 = 0,
    减法 = 1,
    乘法 = 2,
    除法 = 3,
    数量 = 4,
};

inline const char* 张量算子名(张量算子 算子) {
    switch (算子) {
    case 张量算子::加法: return "加法";
    case 张量算子::减法: return "减法";
    case 张量算子::乘法: return "乘法";
    case 张量算子::除法: return "除法";
    default:             return "未知";
    }
}

// 算子 ↔ .spv 文件名（磁盘与生成头都用这个名字，保持英文）
inline const char* 算子到文件名(张量算子 算子) {
    switch (算子) {
    case 张量算子::加法: return "add";
    case 张量算子::减法: return "sub";
    case 张量算子::乘法: return "mul";
    case 张量算子::除法: return "div";
    default:             return "unknown";
    }
}

inline 张量算子 文件名到算子(const std::string& 名称) {
    if (名称 == "add") return 张量算子::加法;
    if (名称 == "sub") return 张量算子::减法;
    if (名称 == "mul") return 张量算子::乘法;
    if (名称 == "div") return 张量算子::除法;
    throw std::runtime_error("未知算子文件名: " + 名称 + ".spv");
}

// ---------------------------------------------------------------------------
// vk张量
// ---------------------------------------------------------------------------
class vk张量 {
public:
    // ---- 构造 / 析构 ----
    vk张量() = default;

    // 默认走调度器持有的逻辑设备：调度器 启动() 之后直接写就行，
    // 张量不拥有设备，只是借用它分配缓冲区与描述符集。
    vk张量(张量布局 布局, 张量类型 类型, std::string 名称 = "tensor",
           bool 读多 = false);

    vk张量(张量布局 布局, 张量类型 类型, const void* 初始数据, std::size_t 字节数,
           std::string 名称 = "tensor", bool 读多 = false);

    // 显式指定设备：只在多设备/测试里用（设备所有权仍在那边，本类不释放）
    vk张量(vk底层::设备& 设备, 张量布局 布局, 张量类型 类型,
           std::string 名称 = "tensor", bool 读多 = false);

    vk张量(vk底层::设备& 设备, 张量布局 布局, 张量类型 类型,
           const void* 初始数据, std::size_t 字节数, std::string 名称 = "tensor",
           bool 读多 = false);

    ~vk张量() = default;

    vk张量(const vk张量&) = delete;
    vk张量& operator=(const vk张量&) = delete;

    vk张量(vk张量&& 其他) noexcept;
    vk张量& operator=(vk张量&& 其他) noexcept;

    // ---- 属性 ----
    const 张量布局& 布局() const { return 布局_; }
    张量类型        类型() const { return 类型_; }
    std::string const& 名称() const { return 名称_; }
    std::size_t     字节大小() const {
        return static_cast<std::size_t>(布局_.元素总数) * 类型字节大小(类型_);
    }
    bool            有效() const { return 缓冲_ != nullptr && 描述符集_ != nullptr; }

    VkBuffer        缓冲句柄() const { return 缓冲_ ? 缓冲_->句柄() : VK_NULL_HANDLE; }
    VkDescriptorSet 描述符集句柄() const {
        return 描述符集_ ? 描述符集_->句柄() : VK_NULL_HANDLE;
    }

    // ---- 布局封装的核心：折算成调度器认识的句柄 ----
    张量句柄 取句柄() const;

    // ---- 形状/类型派生的辅助张量 ----
    // 算子输出几乎总要与输入同形状同类型，这里给一个仿形分配（用本张量自己的设备）
    vk张量 仿形(std::string 新名称 = "输出") const;
    vk底层::设备& 设备() const;

    // ---- 主机数据访问：读写前自动等本张量上在途的算子落地 ----
    void 上传(const void* 数据, std::size_t 字节数);
    void 下载(void* 数据, std::size_t 字节数) const;
    // 持久映射的主机地址；新建后直接写入可省掉 staging 拷贝（写前须确保无在途任务）
    void* 映射() const { return 缓冲_ ? 缓冲_->映射() : nullptr; }
    void 同步() const;                    // 只要「算完了」，不取数据时用（等待不改张量内容）
    bool 有在途任务() const { return 任务_ != 0; }

    // 把外部任务号记到本张量上：多核 pass 写进本张量时用它，
    // 之后 上传/下载/同步/参与运算 都会自动等这个 pass 落地，也自动成为下游前置依赖。
    void 挂任务(std::uint64_t 编号) {
        if (编号 != 0) 同步();            // 别把还在被算子读的缓冲又挂一个新写者
        任务_ = 编号;
    }

    // ---- 张量拷贝：缓冲区对拷，本类自己的活（不借命令流，也不产生任务） ----
    // 拷贝() 返回同形状同类型的新张量；拷贝到() 写进已有张量，函数返回即已搬完。
    vk张量 拷贝(std::string 新名称 = "拷贝") const;
    void   拷贝到(vk张量& 目标) const;

    // ---- 算子：结果是新张量（自带缓冲区），任务编号藏在对象里不外露 ----
    vk张量 operator+(const vk张量& 乙) const { return 算子(张量算子::加法, 乙, "加法"); }
    vk张量 operator-(const vk张量& 乙) const { return 算子(张量算子::减法, 乙, "减法"); }
    vk张量 operator*(const vk张量& 乙) const { return 算子(张量算子::乘法, 乙, "乘法"); }
    vk张量 operator/(const vk张量& 乙) const { return 算子(张量算子::除法, 乙, "除法"); }

    // 一个算子一条具名接口，与操作符完全同实现
    vk张量 加法(const vk张量& 乙) const { return 算子(张量算子::加法, 乙, "加法"); }
    vk张量 减法(const vk张量& 乙) const { return 算子(张量算子::减法, 乙, "减法"); }
    vk张量 乘法(const vk张量& 乙) const { return 算子(张量算子::乘法, 乙, "乘法"); }
    vk张量 除法(const vk张量& 乙) const { return 算子(张量算子::除法, 乙, "除法"); }

    // 通用版：算子由变量决定，或要指定输出名/优先级时走这里（上面八条最终都走它）
    vk张量 算子(张量算子 算子类型, const vk张量& 乙,
                 std::string 新名称 = "结果", int 优先级 = 0) const;

    // ---- 可用性自检：磁盘上的 .spv 与生成头是否都在 ----
    static bool 算子可用(张量算子 算子);
    static void 断言算子可用(张量算子 算子);

private:
    // 建立表达式依赖：把本张量（以及参与运算的另一侧）的在途任务号交给调度器
    std::vector<std::uint64_t> 在途依赖() const {
        if (任务_ == 0) return {};
        return std::vector<std::uint64_t>{任务_};
    }

    vk底层::设备*                     设备_     = nullptr;
    std::shared_ptr<vk底层::缓冲>     缓冲_;
    std::shared_ptr<vk底层::描述符集> 描述符集_;
    张量布局                          布局_;
    张量类型                          类型_     = 张量类型::浮点32;
    std::string                       名称_;
    // 等待与拷贝都不改张量内容，所以 同步() 是 const；编号只是内部记账
    mutable std::uint64_t             任务_     = 0;   // 写进本张量的最后一个任务，0 = 无在途
};

